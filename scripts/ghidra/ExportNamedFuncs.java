/**
 * Export functions from Ghidra into an existing ReXGlue TOML config.
 *
 * Ghidra counterpart of scripts/ida/export_named_funcs.py: reads the TOML,
 * updates entries that already exist, appends new entries for functions not
 * yet in the config and keeps the [functions] section sorted by address.
 * Existing entry metadata (parent, size, ...) is preserved.
 *
 * Built for Ghidra 12.x with the XEXLoaderWV loader. "Named" means any name
 * that is not a Ghidra/loader default (FUN_, Function_, thunk_FUN_ ...):
 * names you typed, Function ID / signature matches and PDB names.
 * Import thunks created by the loader are always skipped; the codegen
 * resolves imports on its own.
 *
 * Usage: Script Manager > ReXGlue > ExportNamedFuncs, pick the TOML that has
 * the [functions] section (the module manifest or one of its includes).
 * Headless: pass the values in askValues order as script arguments.
 *
 * @license BSD 3-Clause License, see LICENSE in the project root.
 */
// @category ReXGlue
// @menupath Tools.ReXGlue.Export Named Functions to TOML

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import ghidra.app.script.GhidraScript;
import ghidra.features.base.values.GhidraValuesMap;
import ghidra.program.model.address.Address;
import ghidra.program.model.address.AddressRange;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionManager;
import ghidra.program.model.mem.MemoryAccessException;
import ghidra.program.model.symbol.RefType;
import ghidra.program.model.symbol.Reference;
import ghidra.program.model.symbol.SourceType;
import ghidra.program.model.symbol.Symbol;

public class ExportNamedFuncs extends GhidraScript {

	// Option names (also the order of headless script arguments).
	private static final String OPT_TOML = "TOML to update";
	private static final String OPT_PREFIX = "Output name prefix";
	private static final String OPT_FILTER = "Name filter (glob)";
	private static final String OPT_EXCLUDE = "Name exclude (glob)";
	private static final String OPT_NAMED = "Export named functions";
	private static final String OPT_FUNC_PTRS = "Export functions only used as pointers";
	private static final String OPT_REMOVE_STALE = "Remove stale entry points";
	private static final String OPT_UPDATE_SIZES = "Update function sizes";
	private static final String OPT_UPDATE_NAMES = "Update function names";
	private static final String OPT_OVERWRITE = "Overwrite input TOML";
	private static final String OPT_SKIP_SAVE_REST = "Skip __save/__rest helpers";
	private static final String OPT_SKIP_NULLSUB = "Skip nullsub";
	private static final String OPT_SKIP_THUNKS = "Skip thunks";

	// Names generated by Ghidra or by XEXLoaderWV, equivalent to IDA's sub_/start.
	private static final String[] DEFAULT_PREFIXES =
		{ "FUN_", "Function_", "thunk_FUN_", "thunk_Function_" };

	// Xbox 360 import thunk: two record words (rewritten by the loader), mtctr r11, bctr.
	private static final int MTCTR_R11 = 0x7D6903A6;
	private static final int BCTR = 0x4E800420;

	// [functions] entry: 0x82C061F0 = { parent = 0x82C03A58, size = 8 }
	private static final Pattern ENTRY_RE =
		Pattern.compile("^(0[xX][0-9a-fA-F]+)\\s*=\\s*\\{(.*)\\}\\s*$");
	// key = value inside the braces (quoted strings, hex or decimal numbers, booleans)
	private static final Pattern KV_RE =
		Pattern.compile("(\\w+)\\s*=\\s*(\"(?:[^\"\\\\]|\\\\.)*\"|0[xX][0-9a-fA-F]+|\\d+|true|false)");

	/** One line of the [functions] section: either a parsed entry or raw text. */
	private static final class Line {
		final boolean isEntry;
		final String raw;
		long addr;
		String addrStr;
		LinkedHashMap<String, String> props;

		Line(String raw) {
			this.isEntry = false;
			this.raw = raw;
		}

		Line(long addr, String addrStr, LinkedHashMap<String, String> props) {
			this.isEntry = true;
			this.raw = null;
			this.addr = addr;
			this.addrStr = addrStr;
			this.props = props;
		}
	}

	/** Name and size collected from Ghidra (name is null for pointer-only functions). */
	private static final class Found {
		final String name;
		final Long size;

		Found(String name, Long size) {
			this.name = name;
			this.size = size;
		}
	}

	@Override
	protected void run() throws Exception {
		GhidraValuesMap values = new GhidraValuesMap();
		values.defineFile(OPT_TOML, null);
		values.defineString(OPT_PREFIX, "rex_");
		values.defineString(OPT_FILTER, "");
		values.defineString(OPT_EXCLUDE, "");
		values.defineBoolean(OPT_NAMED, true);
		values.defineBoolean(OPT_FUNC_PTRS, true);
		values.defineBoolean(OPT_REMOVE_STALE, true);
		values.defineBoolean(OPT_UPDATE_SIZES, true);
		values.defineBoolean(OPT_UPDATE_NAMES, true);
		values.defineBoolean(OPT_OVERWRITE, true);
		values.defineBoolean(OPT_SKIP_SAVE_REST, true);
		values.defineBoolean(OPT_SKIP_NULLSUB, true);
		values.defineBoolean(OPT_SKIP_THUNKS, true);
		askValues("Export Functions to ReXGlue TOML",
			"Updates the [functions] section of a ReXGlue manifest or include file.", values);

		File toml = values.getFile(OPT_TOML);
		if (toml == null || !toml.isFile()) {
			popup("Select an existing TOML file.");
			return;
		}
		String prefix = nz(values.getString(OPT_PREFIX));
		String filter = nz(values.getString(OPT_FILTER));
		String exclude = nz(values.getString(OPT_EXCLUDE));
		boolean doNamed = values.getBoolean(OPT_NAMED);
		boolean doFuncPtrs = values.getBoolean(OPT_FUNC_PTRS);
		boolean removeStale = values.getBoolean(OPT_REMOVE_STALE);
		boolean updateSizes = values.getBoolean(OPT_UPDATE_SIZES);
		boolean updateNames = values.getBoolean(OPT_UPDATE_NAMES);
		boolean overwrite = values.getBoolean(OPT_OVERWRITE);
		boolean skipThunks = values.getBoolean(OPT_SKIP_THUNKS);

		if (!doNamed && !doFuncPtrs) {
			popup("Nothing selected to export.");
			return;
		}

		List<String> ignore = new ArrayList<>(List.of(DEFAULT_PREFIXES));
		if (values.getBoolean(OPT_SKIP_SAVE_REST)) {
			ignore.addAll(List.of("__rest", "__save", "__"));
		}
		if (values.getBoolean(OPT_SKIP_NULLSUB)) {
			ignore.add("nullsub_");
		}
		if (skipThunks) {
			ignore.add("thunk_");
			ignore.add("j_");
		}

		File out = toml;
		if (!overwrite) {
			out = askFile("Save updated TOML config as", "Save");
			if (out == null) {
				return;
			}
		}

		// Step 1 - load the TOML and split out the [functions] section.
		List<String> lines = Files.readAllLines(toml.toPath(), StandardCharsets.UTF_8);
		int sectionStart = -1;
		int sectionEnd = -1;
		for (int i = 0; i < lines.size(); i++) {
			String s = lines.get(i).trim();
			if (s.equals("[functions]")) {
				sectionStart = i;
			}
			else if (sectionStart >= 0 && s.startsWith("[") && s.endsWith("]")) {
				sectionEnd = i;
				break;
			}
		}
		if (sectionStart < 0) {
			popup("No [functions] section found in " + toml.getName() + ".");
			return;
		}
		if (sectionEnd < 0) {
			sectionEnd = lines.size();
		}
		List<Line> funcLines = new ArrayList<>();
		for (int i = sectionStart + 1; i < sectionEnd; i++) {
			Line parsed = parseEntry(lines.get(i));
			funcLines.add(parsed != null ? parsed : new Line(lines.get(i)));
		}

		// Step 2 - collect functions from Ghidra.
		FunctionManager fm = currentProgram.getFunctionManager();
		Set<String> importNames = collectImportNames();
		Map<Long, Found> found = new TreeMap<>();

		if (doNamed) {
			for (Function f : fm.getFunctions(true)) {
				monitor.checkCancelled();
				if (f.isExternal() || (skipThunks && f.isThunk())) {
					continue;
				}
				Symbol sym = f.getSymbol();
				String name = f.getName();
				if (sym == null || sym.getSource() == SourceType.DEFAULT || name.isEmpty() ||
					name.equals("entry")) {
					continue;
				}
				if (startsWithAny(name, ignore) || isImportThunk(f, importNames)) {
					continue;
				}
				if (!filter.isEmpty() && !glob(filter, name)) {
					continue;
				}
				if (!exclude.isEmpty() && glob(exclude, name)) {
					continue;
				}
				found.put(f.getEntryPoint().getOffset(), new Found(name, entrySize(f)));
			}
		}

		if (doFuncPtrs && filter.isEmpty()) {
			for (Function f : fm.getFunctions(true)) {
				monitor.checkCancelled();
				long ea = f.getEntryPoint().getOffset();
				if (found.containsKey(ea) || f.isExternal() || isImportThunk(f, importNames)) {
					continue;
				}
				if (isPointerOnly(f)) {
					found.put(ea, new Found(null, entrySize(f)));
				}
			}
		}

		// Names already claimed in the TOML, so exports do not create duplicates.
		Map<String, Long> usedNames = new HashMap<>();
		for (Line l : funcLines) {
			if (l.isEntry && l.props.containsKey("name")) {
				usedNames.putIfAbsent(unquote(l.props.get("name")), l.addr);
			}
		}
		List<String> duplicates = new ArrayList<>();
		for (Line l : funcLines) {
			if (l.isEntry && l.props.containsKey("name")) {
				String n = unquote(l.props.get("name"));
				Long owner = usedNames.get(n);
				if (owner != null && owner != l.addr) {
					duplicates.add(String.format("'%s': 0x%08X conflicts with 0x%08X (pre-existing)",
						n, l.addr, owner));
					l.props.remove("name");
				}
			}
		}

		// Step 3 - update existing entries.
		int updated = 0;
		int removed = 0;
		List<Line> kept = new ArrayList<>();
		for (Line l : funcLines) {
			if (!l.isEntry) {
				kept.add(l);
				continue;
			}
			Found g = found.remove(l.addr);
			if (g != null) {
				boolean changed = false;
				if (updateNames && g.name != null) {
					String full = prefix + sanitize(g.name);
					String quoted = "\"" + full + "\"";
					if (!quoted.equals(l.props.get("name"))) {
						Long owner = usedNames.get(full);
						if (owner != null && owner != l.addr) {
							duplicates.add(String.format("'%s': 0x%08X conflicts with 0x%08X",
								full, l.addr, owner));
						}
						else {
							String old = l.props.containsKey("name") ? unquote(l.props.get("name")) : null;
							if (old != null && Long.valueOf(l.addr).equals(usedNames.get(old))) {
								usedNames.remove(old);
							}
							l.props.put("name", quoted);
							usedNames.put(full, l.addr);
							changed = true;
						}
					}
				}
				if (updateSizes && g.size != null) {
					String size = String.format("0x%X", g.size);
					if (!size.equals(l.props.get("size"))) {
						l.props.put("size", size);
						changed = true;
					}
				}
				if (changed) {
					updated++;
				}
				kept.add(l);
			}
			else if (removeStale && !l.props.containsKey("parent") && !isFunctionOrRangeStart(l.addr)) {
				// Chunks (entries with parent) are manual config and are never removed.
				removed++;
			}
			else {
				kept.add(l);
			}
		}
		funcLines = kept;

		// Step 4 - add new entries.
		int added = 0;
		for (Map.Entry<Long, Found> e : found.entrySet()) {
			long ea = e.getKey();
			Found g = e.getValue();
			LinkedHashMap<String, String> props = new LinkedHashMap<>();
			if (g.name != null) {
				String full = prefix + sanitize(g.name);
				if (usedNames.containsKey(full)) {
					duplicates.add(String.format("'%s': 0x%08X conflicts with 0x%08X (added without name)",
						full, ea, usedNames.get(full)));
				}
				else {
					props.put("name", "\"" + full + "\"");
					usedNames.put(full, ea);
				}
			}
			if (g.size != null) {
				props.put("size", String.format("0x%X", g.size));
			}
			funcLines.add(new Line(ea, String.format("0x%08X", ea), props));
			added++;
		}

		// Step 5 - write: header lines kept in place, entries sorted by address.
		writeToml(out, lines, sectionStart, sectionEnd, funcLines);

		if (!duplicates.isEmpty()) {
			printerr(duplicates.size() + " duplicate function name(s):");
			for (String d : duplicates) {
				printerr("  " + d);
			}
		}
		String msg = String.format(
			"Export complete.%n  %d existing functions updated (name and/or size)%n" +
				"  %d stale functions removed (invalid entry point)%n  %d new functions added%n%s" +
				"Saved to: %s",
			updated, removed, added,
			duplicates.isEmpty() ? ""
					: "  WARNING: " + duplicates.size() + " duplicate name(s) skipped (see console)\n",
			out.getAbsolutePath());
		println(msg);
		if (!isRunningHeadless()) {
			popup(msg);
		}
	}

	// ── Ghidra helpers ──────────────────────────────────────────────────────

	/** Import names created by XEXLoaderWV: "__imp__X" references name the thunk "X". */
	private Set<String> collectImportNames() {
		Set<String> names = new HashSet<>();
		for (Symbol s : currentProgram.getSymbolTable().getAllSymbols(false)) {
			String n = s.getName();
			if (n.startsWith("__imp__") && n.length() > 7) {
				names.add(n.substring(7));
			}
		}
		return names;
	}

	private boolean isImportThunk(Function f, Set<String> importNames) {
		if (importNames.contains(f.getName())) {
			return true;
		}
		try {
			Address ep = f.getEntryPoint();
			return getInt(ep.add(8)) == MTCTR_R11 && getInt(ep.add(12)) == BCTR;
		}
		catch (MemoryAccessException | RuntimeException e) {
			return false;
		}
	}

	/** Size of the contiguous range that starts at the entry point (IDA: end_ea - start_ea). */
	private Long entrySize(Function f) {
		AddressRange r = f.getBody().getRangeContaining(f.getEntryPoint());
		return r != null ? r.getLength() : null;
	}

	/**
	 * Functions whose address is only taken as a value by code (lis/addi) and never
	 * called or jumped to directly: pointers passed as arguments that codegen can miss.
	 */
	private boolean isPointerOnly(Function f) throws Exception {
		boolean dataFromCode = false;
		for (Reference ref : getReferencesTo(f.getEntryPoint())) {
			monitor.checkCancelled();
			RefType t = ref.getReferenceType();
			if (t.isCall() || t.isJump() || t.isFlow()) {
				return false;
			}
			if (t.isData() || t.isRead() || t.isWrite()) {
				if (getFunctionContaining(ref.getFromAddress()) != null) {
					dataFromCode = true;
				}
			}
		}
		return dataFromCode;
	}

	private boolean isFunctionOrRangeStart(long addr) {
		Address a = toAddr(addr);
		Function f = getFunctionContaining(a);
		if (f == null) {
			return false;
		}
		if (f.getEntryPoint().equals(a)) {
			return true;
		}
		// Equivalent of an IDA chunk start: a body range beginning at this address.
		AddressRange r = f.getBody().getRangeContaining(a);
		return r != null && r.getMinAddress().equals(a);
	}

	// ── TOML / text helpers (same rules as the IDA script) ─────────────────

	private static Line parseEntry(String line) {
		Matcher m = ENTRY_RE.matcher(line.trim());
		if (!m.matches()) {
			return null;
		}
		String addrStr = m.group(1);
		LinkedHashMap<String, String> props = new LinkedHashMap<>();
		Matcher kv = KV_RE.matcher(m.group(2));
		while (kv.find()) {
			props.put(kv.group(1), kv.group(2));
		}
		return new Line(Long.parseLong(addrStr.substring(2), 16), addrStr, props);
	}

	private static String formatEntry(String addrStr, Map<String, String> props) {
		if (props.isEmpty()) {
			return addrStr + " = {}";
		}
		List<String> parts = new ArrayList<>();
		for (String k : List.of("name", "parent", "size")) {
			if (props.containsKey(k)) {
				parts.add(k + " = " + props.get(k));
			}
		}
		for (Map.Entry<String, String> e : props.entrySet()) {
			if (!List.of("name", "parent", "size").contains(e.getKey())) {
				parts.add(e.getKey() + " = " + e.getValue());
			}
		}
		return addrStr + " = { " + String.join(", ", parts) + " }";
	}

	private static void writeToml(File out, List<String> lines, int start, int end,
			List<Line> funcLines) throws IOException {
		List<String> result = new ArrayList<>(lines.subList(0, start + 1));
		List<Line> entries = new ArrayList<>();
		List<String> header = new ArrayList<>();
		for (Line l : funcLines) {
			if (l.isEntry) {
				entries.add(l);
			}
			else if (entries.isEmpty()) {
				header.add(l.raw);
			}
			// Comments/blank lines between entries are dropped, as in the IDA script.
		}
		entries.sort((a, b) -> Long.compareUnsigned(a.addr, b.addr));
		result.addAll(header);
		for (Line l : entries) {
			result.add(formatEntry(l.addrStr, l.props));
		}
		if (end < lines.size()) {
			result.add(""); // keep a blank line before the next section
		}
		result.addAll(lines.subList(end, lines.size()));
		Files.write(out.toPath(), (String.join("\n", result) + "\n").getBytes(StandardCharsets.UTF_8));
	}

	/** Mangled or namespaced name -> valid C/C++ identifier. */
	private static String sanitize(String name) {
		String s = name.replaceAll("[^a-zA-Z0-9_]", "_").replaceAll("_+", "_");
		s = s.replaceAll("^_+|_+$", "");
		if (!s.isEmpty() && Character.isDigit(s.charAt(0))) {
			s = "_" + s;
		}
		return s;
	}

	private static boolean startsWithAny(String name, List<String> prefixes) {
		for (String p : prefixes) {
			if (name.startsWith(p)) {
				return true;
			}
		}
		return false;
	}

	/** fnmatch-style glob (case sensitive): * ? and [...] */
	private static boolean glob(String pattern, String name) {
		StringBuilder re = new StringBuilder();
		for (char c : pattern.toCharArray()) {
			switch (c) {
				case '*' -> re.append(".*");
				case '?' -> re.append('.');
				case '[', ']' -> re.append(c);
				default -> re.append(Pattern.quote(String.valueOf(c)));
			}
		}
		return name.matches(re.toString());
	}

	private static String unquote(String s) {
		return s.length() >= 2 && s.startsWith("\"") && s.endsWith("\"") ? s.substring(1, s.length() - 1) : s;
	}

	private static String nz(String s) {
		return s == null ? "" : s.trim();
	}
}
